import datetime

from django.db import NotSupportedError, utils
from django.db.backends.base.schema import BaseDatabaseSchemaEditor
from django.db.models.fields import AutoFieldMixin

from django_iseries.pybase import job_inquiry_message_reply, run_cl_command, sql_literal

# Changes that can lose data (dropping a column, changing its type) send inquiry message CPA32B2 to the job.
# Its default reply is C (cancel), so they only succeed when the job uses the system reply list
# (INQMSGRPY(*SYSRPYL)) and that list answers CPA32B2 with I.
SCHEMA_INQUIRY_MESSAGE_REPLY = '*SYSRPYL'


class DB2SchemaEditor(BaseDatabaseSchemaEditor):
    """
    Schema editor for Db2 for i. Django's generic implementation does the work; this class only
    supplies Db2 for i syntax and handles what the database can't do directly.
    """

    sql_rename_table = "RENAME TABLE %(old_table)s TO %(new_table)s"
    # Without CASCADE, so dropping a table fails instead of silently dropping dependent views.
    sql_delete_table = "DROP TABLE %(table)s"
    sql_alter_column_type = "ALTER COLUMN %(column)s SET DATA TYPE %(type)s%(collation)s"
    sql_alter_column_identity = (
        "ALTER COLUMN %(column)s SET GENERATED BY DEFAULT AS IDENTITY "
        "(START WITH %(start)d, INCREMENT BY 1, CACHE 10 ORDER)"
    )
    sql_alter_column_drop_identity = "ALTER COLUMN %(column)s DROP IDENTITY"

    def __enter__(self):
        self._restore_inquiry_message_reply = None
        if not self.collect_sql:
            self._use_inquiry_message_reply(SCHEMA_INQUIRY_MESSAGE_REPLY, remember=True)
        return super().__enter__()

    def __exit__(self, exc_type, exc_value, traceback):
        try:
            return super().__exit__(exc_type, exc_value, traceback)
        finally:
            if self._restore_inquiry_message_reply and self.connection.connection is not None:
                self._use_inquiry_message_reply(self._restore_inquiry_message_reply)

    def _use_inquiry_message_reply(self, value, remember=False):
        """Change how this connection's job answers inquiry messages (it affects only this job)."""
        self.connection.ensure_connection()
        cursor = self.connection.connection.cursor()
        try:
            current = job_inquiry_message_reply(cursor)
            if current != value and run_cl_command(cursor, f'CHGJOB INQMSGRPY({value})') and remember:
                self._restore_inquiry_message_reply = current
        finally:
            cursor.close()

    def execute(self, sql, params=()):
        try:
            return super().execute(sql, params)
        except utils.Error as e:
            if e.args and e.args[0] == 'HY008':
                raise utils.OperationalError(
                    f"Db2 for i cancelled {str(sql)!r}. Changes that can lose data send inquiry message CPA32B2, "
                    f"which is answered from the system reply list; add an entry that answers it with I, for "
                    f"example ADDRPYLE SEQNBR(9001) MSGID(CPA32B2) RPY(I) (or OPTIONS['message_replies'])."
                ) from e
            raise

    def quote_value(self, value):
        if isinstance(value, datetime.timedelta):
            # time intervals will be stored as double number of seconds
            return f"{value / datetime.timedelta(seconds=1)}"
        return sql_literal(value)

    def prepare_default(self, value):
        return self.quote_value(value)

    def _rename_field_sql(self, table, old_field, new_field, new_type):
        raise NotSupportedError(
            f"Db2 for i cannot rename columns (renaming {table}.{old_field.column} to {new_field.column}). "
            f"Keep the existing column by setting db_column={old_field.column!r} on the renamed field."
        )

    def _alter_column_type_sql(self, model, old_field, new_field, new_type, old_collation, new_collation):
        old_is_auto = isinstance(old_field, AutoFieldMixin)
        new_is_auto = isinstance(new_field, AutoFieldMixin)
        if new_is_auto:
            # The creation type includes the identity clause; SET DATA TYPE takes the plain type.
            new_type = new_field.rel_db_type(self.connection)
        fragment, other_actions = super()._alter_column_type_sql(
            model, old_field, new_field, new_type, old_collation, new_collation
        )
        table = self.quote_name(model._meta.db_table)
        column = self.quote_name(new_field.column)
        if new_is_auto and not old_is_auto:
            with self.connection.cursor() as cursor:
                cursor.execute(f"SELECT MAX({column}) FROM {table}")
                start = (cursor.fetchone()[0] or 0) + 1
            changes = self.sql_alter_column_identity % {'column': column, 'start': start}
            other_actions.append((self.sql_alter_column % {'table': table, 'changes': changes}, []))
        elif old_is_auto and not new_is_auto:
            changes = self.sql_alter_column_drop_identity % {'column': column}
            other_actions.append((self.sql_alter_column % {'table': table, 'changes': changes}, []))
        return fragment, other_actions
